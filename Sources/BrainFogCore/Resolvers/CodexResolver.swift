import Foundation

/// Models Codex's AGENTS.md discovery, which the Codex app, CLI and IDE
/// extension share. See docs/DESIGN.md §3.
public struct CodexResolver: ContextResolver {
    public let agent = AgentID.codex
    public static let defaultMaxBytes = 32 * 1024

    public init() {}

    public func resolve(workingDirectory: URL, environment env: ResolverEnvironment) -> ResolvedContext {
        let cwd = workingDirectory.standardizedFileURL
        let codexHome = env.codexHome
        let config = CodexConfig(codexHome: codexHome, cwd: cwd)
        // project_root_markers, .git by default; an empty list keeps Codex in cwd.
        let projectRoot = config.hasRoot(above: cwd) ? config.root(of: cwd) : nil
        var list = EntryList(agent: agent)

        // Global: first non-empty of override, then AGENTS.md.
        addFirstNonEmpty(in: codexHome, names: ["AGENTS.override.md", "AGENTS.md"],
                         scope: .user, list: &list)

        // Project: root down to cwd, at most one file per directory, under a byte budget.
        let chain = projectRoot.map { root in
            FileSupport.ancestors(of: cwd).filter { FileSupport.isWithin($0, root) }
        } ?? [cwd]
        if projectRoot == nil {
            list.diagnostics.append(.init(.info, config.rootMarkers == [".git"]
                ? "Not a git repository, so only this folder’s AGENTS.md is read"
                : "No project_root_markers found above this folder, so only its AGENTS.md is read"))
        }
        let names = ["AGENTS.override.md", "AGENTS.md"] + config.fallbackFilenames
        var budget = config.maxBytes
        // An untrusted project gets the user's instructions only
        // (codex-rs core/src/agents_md.rs, `is_untrusted`).
        let untrusted = config.activeTrust(cwd) == false
        for dir in chain {
            for name in names {
                let url = dir.appendingPathComponent(name)
                guard FileSupport.isFile(url), let text = FileSupport.read(url) else { continue }
                if untrusted {
                    list.add(url, scope: .project, timing: .skipped("the project is marked untrusted in Codex"))
                    break
                }
                // Codex picks the first name that exists, then drops it if
                // empty, so an empty override leaves the folder with nothing.
                if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                    list.add(url, scope: .project, timing: .skipped("empty file, and it hides the rest of this folder"))
                    break
                }
                let note = dir.path == cwd.path ? nil : "parent directory"
                if budget <= 0 {
                    list.add(url, scope: .project, timing: .skipped("over project_doc_max_bytes (\(config.maxBytes) bytes)"))
                } else {
                    list.add(url, scope: .project, note: note, visible: Limits.bytes(budget))
                    if list.entries.last?.truncated == true {
                        list.diagnostics.append(.init(.warning,
                            "Project AGENTS.md files total over \(config.maxBytes) bytes; the rest is cut off.", url: url))
                    }
                    budget -= text.utf8.count
                }
                break
            }
        }

        // Memories: generated by Codex and injected at its discretion.
        let memoriesDir = codexHome.appendingPathComponent("memories")
        let memoryTiming: LoadTiming = !config.memoriesEnabled ? .skipped("memories are not enabled")
            : !config.useMemories ? .skipped("memories.use_memories is off")
            : .onDemand("Codex injects relevant memories selectively")
        for url in FileSupport.walk(memoriesDir, maxDepth: 3) {
            list.add(url, scope: .autoMemory, timing: memoryTiming, note: "generated; hand edits are discouraged")
        }
        if config.memoriesEnabled, config.useMemories, let stats = CodexMemoryStore(codexHome: codexHome)?.stats() {
            list.diagnostics.append(.init(.info, stats.rawMemories == 0
                ? "No memories yet. Codex writes them after conversations and brings back the relevant ones later."
                : "Memories from \(stats.rawMemories) past conversations; Codex brings back the relevant ones.",
                topic: .onDemand))
        }

        return list.finish(workingDirectory: cwd, projectRoot: projectRoot)
    }

    private func addFirstNonEmpty(in dir: URL, names: [String], scope: Scope, list: inout EntryList) {
        var chosen = false
        for name in names {
            let url = dir.appendingPathComponent(name)
            guard let text = FileSupport.read(url) else { continue }
            if chosen {
                list.add(url, scope: scope, timing: .skipped("overridden by \(names[0])"))
            } else if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                list.add(url, scope: scope, timing: .skipped("empty file"))
            } else {
                list.add(url, scope: scope)
                chosen = true
            }
        }
    }
}

/// The handful of config.toml keys that affect instructions and skills,
/// from https://learn.chatgpt.com/docs/config-file/config-reference.
/// Reads simple `key = value` lines; not a full TOML parser.
struct CodexConfig {
    var fallbackFilenames: [String] = []
    var maxBytes = CodexResolver.defaultMaxBytes
    var memoriesEnabled = false
    /// `memories.use_memories = false` keeps existing memories out of the prompt.
    var useMemories = true
    var rootMarkers = [".git"]
    /// `projects."<path>".trust_level`, true for "trusted".
    var trust: [String: Bool] = [:]
    /// `[[skills.config]]` entries: a SKILL.md path or a skill name, and
    /// whether it is on. The last match wins.
    var skillSwitches: [(path: String?, name: String?, enabled: Bool)] = []

    init(file: URL) { apply(file) }

    /// The user's config, then each trusted .codex/config.toml from the
    /// project root down to `cwd`, the closest winning. Project files can't
    /// move the root: Codex reads `project_root_markers` from the other layers.
    init(codexHome: URL, cwd: URL) {
        apply(codexHome.appendingPathComponent("config.toml"))
        let root = root(of: cwd)
        for dir in FileSupport.ancestors(of: cwd) where FileSupport.isWithin(dir, root) {
            // codex-rs skips the folder whose .codex is CODEX_HOME.
            guard layerTrust(dir, cwd: cwd) == true,
                  dir.appendingPathComponent(".codex").path != codexHome.standardizedFileURL.path else { continue }
            apply(dir.appendingPathComponent(".codex/config.toml"), project: true)
        }
    }

    /// Whether the user marked `project` trusted, untrusted, or neither.
    static func trust(of project: URL, codexHome: URL) -> Bool? {
        CodexConfig(file: codexHome.appendingPathComponent("config.toml")).activeTrust(project)
    }

    /// The trust that decides whether project AGENTS.md files load: cwd's
    /// entry, else the git root's (codex-rs config `get_active_project`).
    func activeTrust(_ cwd: URL) -> Bool? {
        trust[cwd.standardizedFileURL.path] ?? FileSupport.gitRoot(of: cwd).flatMap { trust[$0.standardizedFileURL.path] }
    }

    /// The trust that decides whether `dir`'s .codex/config.toml applies:
    /// its own entry, else the project root's, else the git root's
    /// (codex-rs config loader `decision_for_dir`).
    func layerTrust(_ dir: URL, cwd: URL) -> Bool? {
        trust[dir.standardizedFileURL.path]
            ?? trust[root(of: cwd).standardizedFileURL.path]
            ?? FileSupport.gitRoot(of: cwd).flatMap { trust[$0.standardizedFileURL.path] }
    }

    /// The nearest folder at or above `cwd` holding a root marker; with no
    /// markers, or none found, `cwd` itself.
    func root(of cwd: URL) -> URL {
        let cwd = cwd.standardizedFileURL
        for dir in FileSupport.ancestors(of: cwd).reversed()
        where rootMarkers.contains(where: { FileSupport.exists(dir.appendingPathComponent($0)) }) {
            return dir
        }
        return cwd
    }

    /// Whether some marker was found, so the folder counts as a project.
    func hasRoot(above cwd: URL) -> Bool {
        FileSupport.ancestors(of: cwd).contains { dir in
            rootMarkers.contains { FileSupport.exists(dir.appendingPathComponent($0)) }
        }
    }

    private mutating func apply(_ file: URL, project: Bool = false) {
        guard let text = FileSupport.read(file) else { return }
        var section = ""
        var pending: (key: String, text: String)?
        for raw in text.components(separatedBy: "\n") {
            let line = Self.stripComment(raw).trimmingCharacters(in: .whitespaces)
            if var acc = pending {
                acc.text += line
                if line.contains("]") { assign(acc.key, acc.text, in: "", project: project); pending = nil }
                else { pending = acc }
                continue
            }
            if line.hasPrefix("[[") {
                section = line.trimmingCharacters(in: CharacterSet(charactersIn: "[] "))
                if section == "skills.config" { skillSwitches.append((nil, nil, true)) }
                continue
            }
            if line.hasPrefix("[") { section = line.trimmingCharacters(in: CharacterSet(charactersIn: "[] ")); continue }
            let parts = line.split(separator: "=", maxSplits: 1).map { $0.trimmingCharacters(in: .whitespaces) }
            guard parts.count == 2 else { continue }
            if section.isEmpty, parts[1].hasPrefix("["), !parts[1].contains("]") {
                pending = (parts[0], parts[1])
                continue
            }
            assign(parts[0], parts[1], in: section, project: project)
        }
    }

    private mutating func assign(_ key: String, _ value: String, in section: String, project: Bool = false) {
        switch (section, key) {
        case ("", "project_root_markers") where project: break
        case ("", "project_doc_fallback_filenames"): fallbackFilenames = Self.strings(value)
        case ("", "project_root_markers"): rootMarkers = Self.strings(value)
        case ("", "project_doc_max_bytes"):
            maxBytes = Int(value.replacingOccurrences(of: "_", with: "")) ?? maxBytes
        case ("features", "memories"), ("", "features.memories"):
            memoriesEnabled = value == "true"
        case ("memories", "use_memories"), ("", "memories.use_memories"):
            useMemories = value != "false"
        case ("skills.config", "path"): skillSwitches[skillSwitches.count - 1].path = Self.strings(value).first
        case ("skills.config", "name"): skillSwitches[skillSwitches.count - 1].name = Self.strings(value).first
        case ("skills.config", "enabled"): skillSwitches[skillSwitches.count - 1].enabled = value != "false"
        case (let s, "trust_level") where s.hasPrefix("projects."):
            let path = String(s.dropFirst("projects.".count)).trimmingCharacters(in: CharacterSet(charactersIn: "\"' "))
            trust[URL(fileURLWithPath: path).standardizedFileURL.path] = Self.strings(value).first == "trusted"
        default: break
        }
    }

    /// Whether `[[skills.config]]` turns the skill off.
    func skillDisabled(name: String, file: URL) -> Bool {
        var on = true
        for s in skillSwitches where s.path.map({ URL(fileURLWithPath: $0).standardizedFileURL.path == file.standardizedFileURL.path })
            ?? (s.name == name) {
            on = s.enabled
        }
        return !on
    }

    /// Drops a `#` comment, but not a `#` inside a quoted string.
    private static func stripComment(_ line: String) -> String {
        var quote: Character?
        var escaped = false
        for (i, c) in zip(line.indices, line) {
            if escaped { escaped = false; continue }
            if let q = quote {
                if c == "\\" && q == "\"" { escaped = true } else if c == q { quote = nil }
            } else if c == "\"" || c == "'" {
                quote = c
            } else if c == "#" {
                return String(line[..<i])
            }
        }
        return line
    }

    private static func strings(_ s: String) -> [String] { CodexMCPToml.strings(in: s) }
}
