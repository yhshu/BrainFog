import Foundation

/// Models Codex's AGENTS.md discovery. See docs/DESIGN.md §3.
public struct CodexResolver: ContextResolver {
    public let agent = AgentID.codex
    public static let defaultMaxBytes = 32 * 1024

    public init() {}

    public func resolve(workingDirectory: URL, environment env: ResolverEnvironment) -> ResolvedContext {
        let cwd = workingDirectory.standardizedFileURL
        let codexHome = env.variables["CODEX_HOME"].map {
            URL(fileURLWithPath: FileSupport.expandTilde($0, home: env.home))
        } ?? env.home.appendingPathComponent(".codex")
        let config = CodexConfig(file: codexHome.appendingPathComponent("config.toml"))
        let projectRoot = FileSupport.gitRoot(of: cwd)
        var list = EntryList(agent: agent)

        // Global: first non-empty of override, then AGENTS.md.
        addFirstNonEmpty(in: codexHome, names: ["AGENTS.override.md", "AGENTS.md"],
                         scope: .user, list: &list)

        // Project: root down to cwd, at most one file per directory, under a byte budget.
        let chain = projectRoot.map { root in
            FileSupport.ancestors(of: cwd).filter { FileSupport.isWithin($0, root) }
        } ?? [cwd]
        if projectRoot == nil {
            list.diagnostics.append(.init(.info, "Not a git repository, so only this folder’s AGENTS.md is read"))
        }
        let names = ["AGENTS.override.md", "AGENTS.md"] + config.fallbackFilenames
        var budget = config.maxBytes
        for dir in chain {
            for name in names {
                let url = dir.appendingPathComponent(name)
                guard FileSupport.isFile(url), let text = FileSupport.read(url) else { continue }
                // Codex passes over an empty file; list it so it can still be opened.
                if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                    list.add(url, scope: .project, timing: .skipped("empty file"))
                    continue
                }
                let note = dir.path == cwd.path ? nil : "parent directory"
                if budget <= 0 {
                    list.add(url, scope: .project, timing: .skipped("over project_doc_max_bytes (\(config.maxBytes) bytes)"))
                } else {
                    list.add(url, scope: .project, note: note, visible: Limits.bytes(budget))
                    if list.entries.last?.truncated == true {
                        list.diagnostics.append(.init(.warning,
                            "Project AGENTS.md files total over \(config.maxBytes) bytes; the rest is cut off.", url: url))
                    }
                    budget -= text.utf8.count
                }
                break
            }
        }

        // Memories: generated by Codex and injected at its discretion.
        let memoriesDir = codexHome.appendingPathComponent("memories")
        let memoryTiming: LoadTiming = config.memoriesEnabled
            ? .onDemand("Codex injects relevant memories selectively") : .skipped("memories are not enabled")
        for url in FileSupport.walk(memoriesDir, maxDepth: 3) {
            list.add(url, scope: .autoMemory, timing: memoryTiming, note: "generated; hand edits are discouraged")
        }
        if config.memoriesEnabled, let stats = CodexMemoryStore(codexHome: codexHome)?.stats() {
            list.diagnostics.append(.init(.info, stats.rawMemories == 0
                ? "No memories yet. Codex writes them after conversations and brings back the relevant ones later."
                : "Memories from \(stats.rawMemories) past conversations; Codex brings back the relevant ones.",
                topic: .onDemand))
        }

        return list.finish(workingDirectory: cwd, projectRoot: projectRoot)
    }

    private func addFirstNonEmpty(in dir: URL, names: [String], scope: Scope, list: inout EntryList) {
        var chosen = false
        for name in names {
            let url = dir.appendingPathComponent(name)
            guard let text = FileSupport.read(url) else { continue }
            if chosen {
                list.add(url, scope: scope, timing: .skipped("overridden by \(names[0])"))
            } else if text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                list.add(url, scope: scope, timing: .skipped("empty file"))
            } else {
                list.add(url, scope: scope)
                chosen = true
            }
        }
    }
}

/// The handful of `~/.codex/config.toml` keys that affect instructions.
/// Reads simple `key = value` lines; not a full TOML parser.
struct CodexConfig {
    var fallbackFilenames: [String] = []
    var maxBytes = CodexResolver.defaultMaxBytes
    var memoriesEnabled = false

    init(file: URL) {
        guard let text = FileSupport.read(file) else { return }
        var section = ""
        var pendingArray: String?
        for raw in text.components(separatedBy: "\n") {
            let line = Self.stripComment(raw).trimmingCharacters(in: .whitespaces)
            if var acc = pendingArray {
                acc += line
                if line.contains("]") { fallbackFilenames = Self.strings(acc); pendingArray = nil }
                else { pendingArray = acc }
                continue
            }
            if line.hasPrefix("[") { section = line.trimmingCharacters(in: CharacterSet(charactersIn: "[]")); continue }
            let parts = line.split(separator: "=", maxSplits: 1).map { $0.trimmingCharacters(in: .whitespaces) }
            guard parts.count == 2 else { continue }
            switch (section, parts[0]) {
            case ("", "project_doc_fallback_filenames"):
                if parts[1].contains("]") { fallbackFilenames = Self.strings(parts[1]) }
                else { pendingArray = parts[1] }
            case ("", "project_doc_max_bytes"):
                maxBytes = Int(parts[1].replacingOccurrences(of: "_", with: "")) ?? maxBytes
            case ("features", "memories"), ("", "features.memories"):
                memoriesEnabled = parts[1] == "true"
            default: break
            }
        }
    }

    /// Drops a `#` comment, but not a `#` inside a quoted string.
    private static func stripComment(_ line: String) -> String {
        var quote: Character?
        var escaped = false
        for (i, c) in zip(line.indices, line) {
            if escaped { escaped = false; continue }
            if let q = quote {
                if c == "\\" && q == "\"" { escaped = true } else if c == q { quote = nil }
            } else if c == "\"" || c == "'" {
                quote = c
            } else if c == "#" {
                return String(line[..<i])
            }
        }
        return line
    }

    private static func strings(_ s: String) -> [String] {
        let re = try! NSRegularExpression(pattern: #""([^"]*)"|'([^']*)'"#)
        return re.matches(in: s, range: NSRange(s.startIndex..., in: s)).compactMap { m in
            [1, 2].lazy.compactMap { Range(m.range(at: $0), in: s) }.first.map { String(s[$0]) }
        }
    }
}
