import AppKit
import SwiftUI
import BrainFogCore

/// Edits one context file in place. Refuses to overwrite a file that
/// changed on disk since it was opened, unless the user says so.
struct EditorView: View {
    @Environment(AppModel.self) private var model
    let entry: ContextEntry

    @State private var text = ""
    @State private var original = ""
    @State private var loadedModified: Date?
    @State private var error: String?
    @State private var conflict = false

    private var isDirty: Bool { text != original }
    private var isGenerated: Bool { entry.agent == .codex && entry.scope == .autoMemory }

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            VStack(alignment: .leading, spacing: 4) {
                HStack {
                    Image(systemName: entry.scope.symbol).foregroundStyle(entry.agent.tint)
                    Text(entry.url.lastPathComponent).font(.headline)
                    ScopeChip(scope: entry.scope)
                    Spacer()
                }
                Text(entry.url.path).font(.caption).foregroundStyle(.secondary)
                    .textSelection(.enabled).lineLimit(2).truncationMode(.middle)
                if isGenerated {
                    Label("Generated by Codex; OpenAI discourages hand edits", systemImage: "exclamationmark.triangle")
                        .font(.caption).foregroundStyle(.orange)
                }
                if let error {
                    Label(error, systemImage: "xmark.octagon").font(.caption).foregroundStyle(.red)
                }
            }
            .padding(16)

            TextEditor(text: $text)
                .font(.system(.body, design: .monospaced))
                .scrollContentBackground(.hidden)
                .padding(.horizontal, 12)
                .disabled(!entry.url.isFileURL)
        }
        .toolbar {
            ToolbarItemGroup {
                Button("Show in Finder", systemImage: "folder") {
                    NSWorkspace.shared.activateFileViewerSelecting([entry.url])
                }
                Button("Revert", systemImage: "arrow.uturn.backward") { text = original }
                    .disabled(!isDirty)
                Button("Save", systemImage: "square.and.arrow.down") { save(force: false) }
                    .keyboardShortcut("s")
                    .buttonStyle(.glassProminent)
                    .tint(entry.agent.tint)
                    .disabled(!isDirty)
            }
        }
        .task { load() }
        .alert("The file changed on disk", isPresented: $conflict) {
            Button("Overwrite", role: .destructive) { save(force: true) }
            Button("Reload") { load() }
            Button("Cancel", role: .cancel) {}
        } message: {
            Text("Another program, possibly the agent itself, changed this file after you opened it. Overwriting discards those changes.")
        }
    }

    private func modified() -> Date? {
        (try? FileManager.default.attributesOfItem(atPath: entry.url.path))?[.modificationDate] as? Date
    }

    private func load() {
        guard entry.url.isFileURL else {
            text = "Remote instructions: \(entry.url.absoluteString)"
            original = text
            return
        }
        do {
            text = try String(contentsOf: entry.url, encoding: .utf8)
            original = text
            loadedModified = modified()
            error = nil
        } catch {
            self.error = "Couldn’t read the file: \(error.localizedDescription)"
        }
    }

    private func save(force: Bool) {
        if !force, let loaded = loadedModified, let now = modified(), now > loaded {
            conflict = true
            return
        }
        do {
            try text.write(to: entry.url, atomically: true, encoding: .utf8)
            original = text
            loadedModified = modified()
            error = nil
            model.resolve()
        } catch {
            self.error = "Couldn’t save: \(error.localizedDescription)"
        }
    }
}
